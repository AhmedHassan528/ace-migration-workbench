/* Eclipse Java project generator for a JAR recovered from a BAR.
 *
 *   <Project>/src/<package path>/<Class>.java   decompiled source (complete or clearly-marked partial),
 *                                               or original .java files found in the BAR
 *   <Project>/bin/<package path>/<Class>.class  the ORIGINAL compiled classes from the JAR (byte-identical)
 *   <Project>/Lib/*.jar                         dependency JARs (e.g. the database driver) and, optionally,
 *                                               the original application JAR (kept off the build path)
 *   <Project>/.project, .classpath              generated only from evidence (see reasons below)
 *   <Project>/.settings/org.eclipse.jdt.core.prefs   compiler level taken from the class-file version
 *
 * A .class file is never renamed to .java and bytecode is never copied into a source file. */
(function (ACE) {
  'use strict';
  var util = ACE.util, T = ACE.dtypes;
  var EP = ACE.eclipse = {};

  var GEN = 'Generated by IBM ACE Migration Workbench from a BAR file (not the original Eclipse metadata).';

  /* Evidence-based description of the project (used by the UI before export). */
  EP.plan = function (ws, jarRec, opts) {
    opts = opts || {};
    var d = ws.decompiled && ws.decompiled[jarRec.sha256];
    var name = (opts.projectName || (d && d.projectName) || util.stripExt(jarRec.name)).replace(/[^\w.\-]/g, '_');
    var classes = jarRec.info.classes;
    var majors = classes.map(function (c) { return c.major; });
    var maxMajor = majors.length ? Math.max.apply(null, majors) : 52;
    var level = opts.target === 'ace13' ? '17' : (ACE.java.javaVersionOf(maxMajor) === '1.1' ? '1.8' : ACE.java.javaVersionOf(Math.max(maxMajor, 52)));
    if (level === '8') level = '1.8';
    var usesAce = classes.some(function (c) { return c.classRefs.some(function (r) { return /^com\/ibm\/broker\//.test(r); }); });
    var jcn = classes.some(function (c) { return c.superName === 'com/ibm/broker/javacompute/MbJavaComputeNode'; });
    // dependency JARs: the other JARs deployed in the same container(s) as this JAR
    var containers = new Set(jarRec.occurrences.map(function (o) { return o.indexOf('!/') >= 0 ? o.slice(0, o.lastIndexOf('!/')) : ''; }));
    var deps = (ws.jars || []).filter(function (j) {
      if (j === jarRec) return false;
      return j.occurrences.some(function (o) { return containers.has(o.indexOf('!/') >= 0 ? o.slice(0, o.lastIndexOf('!/')) : ''); });
    });
    if (opts.includeExcluded) (ws.jars || []).forEach(function (j) { if (j !== jarRec && !j.decision.selected && deps.indexOf(j) < 0) deps.push(j); });
    var reasons = [];
    reasons.push('.project: Java nature because the JAR contains ' + classes.length + ' class file(s)' + (jcn ? '; ACE JavaCompute nature/builders because ' + classes.filter(function (c) { return c.superName === 'com/ibm/broker/javacompute/MbJavaComputeNode'; }).map(function (c) { return c.name.replace(/\//g, '.'); }).join(', ') + ' extends MbJavaComputeNode' : ''));
    reasons.push('.classpath: src + bin output; JRE ' + (opts.target === 'ace13' ? 'JavaSE-17 (ACE 13 target)' : 'JavaSE-' + level + ' (class files are major version ' + maxMajor + ')') + (deps.length ? '; Lib/' + deps.map(function (j) { return j.name; }).join(', Lib/') + ' (deployed next to this JAR in the BAR)' : '') + (usesAce ? '; ACE plug-in API (JCN_HOME/jplugin2.jar, javacompute.jar) because the bytecode references com.ibm.broker.*' : ''));
    reasons.push('.settings: compiler compliance ' + level + (opts.target === 'ace13' ? ' (ACE 13 runs Java 17)' : ' (from the class-file version)'));
    return { name: name, level: level, maxMajor: maxMajor, usesAce: usesAce, jcn: jcn, deps: deps, reasons: reasons, decompiled: d || null };
  };

  function projectXml(p) {
    var builders = ['org.eclipse.jdt.core.javabuilder'], natures = ['org.eclipse.jdt.core.javanature'];
    if (p.jcn || p.usesAce) { builders.push('com.ibm.etools.mft.java.builder.javabuilder', 'com.ibm.etools.mft.jcn.jcnbuilder'); natures.push('com.ibm.etools.mft.jcn.jcnnature'); }
    var x = ['<?xml version="1.0" encoding="UTF-8"?>', '<projectDescription>', '\t<name>' + util.esc(p.name) + '</name>', '\t<comment>' + GEN + '</comment>', '\t<projects>', '\t</projects>', '\t<buildSpec>'];
    builders.forEach(function (b) { x.push('\t\t<buildCommand>', '\t\t\t<name>' + b + '</name>', '\t\t\t<arguments>', '\t\t\t</arguments>', '\t\t</buildCommand>'); });
    x.push('\t</buildSpec>', '\t<natures>');
    natures.forEach(function (n) { x.push('\t\t<nature>' + n + '</nature>'); });
    x.push('\t</natures>', '</projectDescription>', '');
    return x.join('\n');
  }
  function classpathXml(p, target) {
    var jre = target === 'ace13' ? 'JavaSE-17' : 'JavaSE-' + p.level;
    var x = ['<?xml version="1.0" encoding="UTF-8"?>', '<!-- ' + GEN + ' -->', '<classpath>',
      '\t<classpathentry kind="src" path="src"/>',
      '\t<classpathentry kind="con" path="org.eclipse.jdt.launching.JRE_CONTAINER/org.eclipse.jdt.internal.debug.ui.launcher.StandardVMType/' + jre + '"/>'];
    p.deps.forEach(function (j) { x.push('\t<classpathentry kind="lib" path="Lib/' + util.esc(j.name) + '"/>'); });
    if (p.usesAce) { x.push('\t<classpathentry kind="var" path="JCN_HOME/javacompute.jar"/>', '\t<classpathentry kind="var" path="JCN_HOME/jplugin2.jar"/>'); }
    x.push('\t<classpathentry kind="output" path="bin"/>', '</classpath>', '');
    return x.join('\n');
  }
  function prefs(p, target) {
    var lv = target === 'ace13' ? '17' : p.level;
    return ['# ' + GEN, 'eclipse.preferences.version=1', 'org.eclipse.jdt.core.compiler.codegen.targetPlatform=' + lv, 'org.eclipse.jdt.core.compiler.compliance=' + lv, 'org.eclipse.jdt.core.compiler.source=' + lv, ''].join('\n');
  }

  /* Produce the project's files. overlay: {path: text} working-copy changes (ACE 13). */
  EP.files = function (ws, jarRec, opts) {
    opts = opts || {};
    var p = EP.plan(ws, jarRec, opts), out = [], root = p.name + '/';
    out.push({ path: root + '.project', data: projectXml(p), origin: 'generated', note: p.reasons[0] });
    out.push({ path: root + '.classpath', data: classpathXml(p, opts.target), origin: 'generated', note: p.reasons[1] });
    out.push({ path: root + '.settings/org.eclipse.jdt.core.prefs', data: prefs(p, opts.target), origin: 'generated', note: p.reasons[2] });
    // src: decompiled sources (complete + partial). Failed classes produce no file.
    var srcCount = 0, partial = 0;
    if (p.decompiled) p.decompiled.results.forEach(function (r) {
      if (!r.source) return;
      var path = root + 'src/' + r.path, ov = opts.overlay && opts.overlay[path];
      var header = '// Decompiled from ' + jarRec.name + ' by the ' + p.decompiled.engine + ' (' + r.status.toUpperCase() + ').\n' +
        (r.status !== 'complete' ? '// PARTIAL: some members could not be recovered - search for "WORKBENCH DECOMPILER" below.\n' : '') +
        '// This is a reconstruction from bytecode, not the original source file.\n';
      out.push({ path: path, data: ov ? ov.text : header + r.source, origin: ov ? (ov.origin || 'transformed') : 'decompiled', note: r.status + (ov ? '; changed in working copy' : ''), original: ov ? header + r.source : null });
      srcCount++; if (r.status !== 'complete') partial++;
    });
    // bin: original class files, byte-identical, at their package paths
    jarRec.info.classes.forEach(function (c) { if (c.bytes) out.push({ path: root + 'bin/' + c.path, data: c.bytes, origin: 'original', note: 'original bytecode from ' + jarRec.name }); });
    // Lib: dependencies (+ original application JAR, kept off the build path)
    var file = function (j) { return ws.files.filter(function (f) { return f.id === j.fileIds[0]; })[0]; };
    p.deps.forEach(function (j) { var f = file(j); if (f && f.bytes) out.push({ path: root + 'Lib/' + j.name, data: f.bytes, origin: 'original', note: 'dependency on the build path' + (j.classification.type === 'driver' ? ' (database driver, not decompiled)' : '') }); });
    if (opts.keepOriginalJar !== false) { var f0 = file(jarRec); if (f0 && f0.bytes && !p.deps.some(function (j) { return j.name === jarRec.name; })) out.push({ path: root + 'Lib/' + jarRec.name, data: f0.bytes, origin: 'original', note: 'original application JAR, NOT on the build path (its classes are rebuilt from src)' }); }
    return { plan: p, files: out, srcCount: srcCount, partial: partial };
  };

  /* Stand-alone ZIP of one project. */
  EP.zip = async function (ws, jarRec, opts) {
    var r = EP.files(ws, jarRec, opts), w = new ACE.zip.Writer();
    r.files.forEach(function (f) { w.add(f.path, f.data); });
    w.add(r.plan.name + '/PROJECT-RECOVERY-NOTES.txt', EP.notes(ws, jarRec, r));
    return { blob: await w.build(), result: r };
  };

  EP.notes = function (ws, jarRec, r) {
    var d = r.plan.decompiled, L = [];
    L.push('Project ' + r.plan.name + ' recovered from ' + jarRec.name + ' (sha256 ' + jarRec.sha256 + ')', '');
    L.push('Stages:');
    L.push('  JAR extracted from BAR ......... yes (' + jarRec.occurrences.join(', ') + ')');
    L.push('  JAR inspected .................. ' + (jarRec.info.error ? 'FAILED: ' + jarRec.info.error : 'yes'));
    L.push('  Classes detected ............... ' + jarRec.info.classCount);
    L.push('  Java source generated .......... ' + (d ? d.stats.complete + ' complete, ' + d.stats.partial + ' partial, ' + d.stats.failed + ' failed (engine: ' + d.engine + ')' : 'NOT RUN'));
    L.push('  Source files in this project ... ' + r.srcCount + (r.partial ? ' (' + r.partial + ' partial)' : ''), '');
    L.push('Why each generated file exists:'); r.plan.reasons.forEach(function (x) { L.push('  - ' + x); });
    if (d) { L.push('', 'Per class:'); d.results.forEach(function (x) { L.push('  ' + x.className.replace(/\//g, '.') + ': ' + x.status.toUpperCase() + (x.notes.length ? ' - ' + x.notes.join('; ') : '') + x.methods.filter(function (m) { return m.status !== 'ok'; }).map(function (m) { return '\n      method ' + m.name + ' NOT recovered: ' + m.reason; }).join('')); }); }
    L.push('', 'Import: File > Import > General > Existing Projects into Workspace > Select archive file.', 'The decompiled source must be reviewed and compiled in your IDE/Toolkit; the workbench cannot run a compiler.');
    return L.join('\r\n') + '\r\n';
  };
})(window.ACE);
