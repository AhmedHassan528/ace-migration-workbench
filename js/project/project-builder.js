/* Importable project generation.
 *
 * layout(ws)            - maps every extracted file to <Project>/<relative path> (no content changes)
 * buildPackage(ws, ...) - produces the ACE 12 or ACE 13 output ZIP + manifest
 *
 * Provenance of every output file is recorded in MANIFEST.json:
 *   original           byte-identical copy of a BAR entry
 *   original-metadata  BAR/container META-INF (kept under _bar-metadata/, not part of a project)
 *   decompiled         produced by the workbench decompiler from a JAR in the BAR (not original source)
 *   generated          created by the workbench (e.g. .project) - labelled inside the file
 *   transformed        original or decompiled file changed by an approved migration fix
 *   user-edited        changed by the user in the Source Explorer
 *   report             workbench report */
(function (ACE) {
  'use strict';
  var util = ACE.util;
  var proj = ACE.project = {};

  var GEN_COMMENT = 'Generated by IBM ACE Migration Workbench from a BAR file - NOT the original Toolkit metadata. Validate by importing into the Toolkit.';

  proj.layout = function (ws) {
    if (ws._layout) return ws._layout;
    var out = { projects: [], files: [], metadata: [], unassigned: [], notes: [] };
    var deps = (ws.model && ws.model.deployables) || [];
    var nameUse = {};
    if (ws.inputKind === 'workspace') {
      // Toolkit workspace ZIP: every project folder is kept exactly as it is (original .project,
      // .classpath, .settings, META-INF); paths are relative to the project folder.
      var fileById = {}; ws.files.forEach(function (f) { fileById[f.id] = f; });
      deps.forEach(function (d) {
        var pname = d.name;
        if (nameUse[pname]) { out.notes.push('Two folders declare the project name "' + pname + '" (' + nameUse[pname].vpath + ', ' + d.vpath + '); the second was exported as "' + d.folder + '__dup". Resolve this manually.'); pname = d.folder + '__dup'; }
        nameUse[pname] = d;
        out.projects.push({ name: pname, type: d.type, deployableId: d.id, containerVPath: d.vpath, descriptor: d.descriptor, parentDeployableId: null, generated: [], eclipse: d.eclipse, original: true });
        d.fileIds.forEach(function (id) {
          var f = fileById[id]; if (!f || f.isContainer) return;
          var rel = f.path.slice(d.projectRoot.length);
          if (f.duplicate) { out.unassigned.push({ fileId: f.id, outPath: '_conflicts/' + f.vpath.replace(/#/g, '_'), note: 'duplicate archive entry' }); return; }
          out.files.push({ fileId: f.id, project: pname, relPath: rel, outPath: pname + '/' + rel });
        });
      });
      (ws.model.looseFiles || []).forEach(function (id) { var f = fileById[id]; if (f) out.unassigned.push({ fileId: f.id, outPath: '_unassigned/' + f.path }); });
      ws._layout = out;
      return out;
    }
    deps.forEach(function (d) {
      if (['application', 'static-library', 'library', 'shared-library'].indexOf(d.type) < 0) return;
      var files = ACE.bar.filesIn(ws, d.containerId);
      var pname = d.name;
      if (nameUse[pname]) {
        // Same project name from two containers: identical content => merge, else rename.
        var other = nameUse[pname];
        var sig = function (fs) { return fs.filter(function (f) { return !/^meta-inf\//i.test(f.path); }).map(function (f) { return f.path + ':' + f.sha256; }).sort().join('|'); };
        if (sig(files) === sig(ACE.bar.filesIn(ws, other.containerId))) {
          out.notes.push('Library "' + pname + '" is contained in more than one application with identical content; exported once.');
          d.mergedInto = other.id; return;
        }
        var newName = pname + '__' + util.stripExt((ACE.bar.container(ws, ACE.bar.container(ws, d.containerId).parentId) || {}).name || 'dup');
        out.notes.push('Library "' + pname + '" appears with DIFFERENT content in more than one container; the copy from ' + d.vpath + ' was exported as project "' + newName + '". Resolve this manually.');
        pname = newName;
      }
      nameUse[pname] = d;
      var p = { name: pname, type: d.type, deployableId: d.id, containerVPath: d.vpath, descriptor: d.descriptor, parentDeployableId: d.parentDeployableId, generated: [] };
      out.projects.push(p);
      files.forEach(function (f) {
        if (/^meta-inf\//i.test(f.path)) { out.metadata.push({ fileId: f.id, outPath: '_bar-metadata/' + pname + '/' + f.path }); return; }
        if (f.isContainer) return; // nested libzip becomes its own project
        out.files.push({ fileId: f.id, project: pname, relPath: f.path, outPath: pname + '/' + f.path });
      });
    });
    var root = ws.containers[0];
    if (root) ACE.bar.filesIn(ws, root.id).forEach(function (f) {
      if (/^meta-inf\//i.test(f.path)) out.metadata.push({ fileId: f.id, outPath: '_bar-metadata/BAR/' + f.path });
      else if (!f.isContainer) out.unassigned.push({ fileId: f.id, outPath: '_unassigned/' + f.path });
    });
    // Duplicate entries and failed extractions are never mixed into projects
    ws.files.forEach(function (f) {
      if (f.duplicate) {
        out.files = out.files.filter(function (x) { return x.fileId !== f.id; });
        out.unassigned.push({ fileId: f.id, outPath: '_conflicts/' + f.vpath.replace(/!\//g, '/').replace(/#/g, '_') , note: 'duplicate archive entry' });
      }
    });
    ws._layout = out;
    return out;
  };

  function projectFile(name, comment, refs, natures, builders) {
    var x = ['<?xml version="1.0" encoding="UTF-8"?>', '<projectDescription>', '\t<name>' + util.esc(name) + '</name>', '\t<comment>' + util.esc(comment) + '</comment>', '\t<projects>'];
    refs.forEach(function (r) { x.push('\t\t<project>' + util.esc(r) + '</project>'); });
    x.push('\t</projects>', '\t<buildSpec>');
    builders.forEach(function (b) { x.push('\t\t<buildCommand>', '\t\t\t<name>' + b + '</name>', '\t\t\t<arguments>', '\t\t\t</arguments>', '\t\t</buildCommand>'); });
    x.push('\t</buildSpec>', '\t<natures>');
    natures.forEach(function (n) { x.push('\t\t<nature>' + n + '</nature>'); });
    x.push('\t</natures>', '</projectDescription>', '');
    return x.join('\n');
  }

  var MB_BUILDERS = ['com.ibm.etools.mft.applib.applibbuilder', 'com.ibm.etools.mft.applib.applibresourcevalidator', 'com.ibm.etools.mft.connector.policy.ui.PolicyBuilder', 'com.ibm.etools.mft.applib.mbprojectbuilder', 'com.ibm.etools.msg.validation.dfdl.mlibdfdlbuilder', 'com.ibm.etools.mft.flow.adapters.adapterbuilder', 'com.ibm.etools.mft.flow.sca.scabuilder', 'com.ibm.etools.msg.validation.dfdl.mbprojectresourcesbuilder', 'com.ibm.etools.mft.esql.lang.esqllangbuilder', 'com.ibm.etools.mft.map.builder.mslmappingbuilder', 'com.ibm.etools.mft.flow.msgflowxsltbuilder', 'com.ibm.etools.mft.flow.msgflowbuilder', 'com.ibm.etools.mft.decision.service.ui.decisionservicerulebuilder', 'com.ibm.etools.mft.pattern.capture.PatternBuilder', 'com.ibm.etools.mft.json.builder.JSONBuilder', 'com.ibm.etools.mft.restapi.ui.restApiDefinitionsBuilder', 'com.ibm.etools.mft.policy.ui.policybuilder', 'com.ibm.etools.mft.msg.assembly.messageAssemblyBuilder', 'com.ibm.etools.msg.validation.dfdl.dfdlqnamevalidator', 'com.ibm.etools.mft.bar.ext.barbuilder', 'com.ibm.etools.mft.unittest.ui.TestCaseBuilder'];
  var JAVA_BUILDERS = ['org.eclipse.jdt.core.javabuilder', 'com.ibm.etools.mft.java.builder.javabuilder', 'com.ibm.etools.mft.jcn.jcnbuilder', 'com.ibm.etools.mft.bar.ext.barbuilder'];

  /* Generated .project for an application/library project that has none in the BAR.
   * Returns {text, note}, {text:null, note} for shared libraries, or null when the BAR has its own. */
  proj.generatedProjectFile = function (ws, p, refs) {
    var lay = proj.layout(ws);
    if (lay.files.some(function (l) { return l.project === p.name && l.relPath === '.project'; })) return null;
    var rr = refs[p.name] || [], r = rr.map(function (x) { return x.project; });
    var why = rr.map(function (x) { return x.project + ' (' + x.reasons.join('; ') + ')'; }).join(', ');
    if (p.type === 'application') return { text: projectFile(p.name, GEN_COMMENT, r, ['com.ibm.etools.msgbroker.tooling.applicationNature', 'com.ibm.etools.msgbroker.tooling.messageBrokerProjectNature'], MB_BUILDERS), note: 'Application project file. References: ' + why };
    if (p.type === 'static-library' || p.type === 'library') return { text: projectFile(p.name, GEN_COMMENT, r, ['com.ibm.etools.msgbroker.tooling.libraryNature', 'com.ibm.etools.msgbroker.tooling.messageBrokerProjectNature'], MB_BUILDERS), note: 'Library project file. References: ' + why };
    return { text: null, note: 'Shared library: no .project generated (shared-library project metadata cannot be reconstructed reliably). Create a Shared Library project named "' + p.name + '" in the Toolkit and copy the files in.' };
  };

  /* Project references: application -> its static libraries; any project -> projects whose
   * subflows / ESQL modules it uses (inferred from resolved references). */
  proj.references = function (ws, facts) {
    var lay = proj.layout(ws), refs = {};
    lay.projects.forEach(function (p) { refs[p.name] = { set: {}, why: {} }; });
    function add(from, to, why) { if (!from || !to || from === to || !refs[from]) return; refs[from].set[to] = true; (refs[from].why[to] = refs[from].why[to] || []).push(why); }
    // Workspace ZIP: the references declared in each original .project come first.
    lay.projects.forEach(function (p) {
      if (!p.eclipse) return;
      (p.eclipse.dotProject.projects || []).forEach(function (r) {
        if (!refs[p.name]) return;
        refs[p.name].set[r] = true;
        (refs[p.name].why[r] = refs[p.name].why[r] || []).push(refs[r] ? 'declared in .project' : 'declared in .project - PROJECT NOT IN THE INPUT');
      });
    });
    lay.projects.forEach(function (p) {
      if (p.type !== 'application') return;
      lay.projects.forEach(function (q) { if (q.parentDeployableId === p.deployableId) add(p.name, q.name, 'static library contained in the application archive'); });
    });
    if (facts) {
      facts.flows.forEach(function (fl) {
        fl.subflowRefs.forEach(function (s) { (s.resolvedTo || []).forEach(function (r) { add(fl.project, r.split('/')[0], 'uses subflow ' + s.path); }); });
        fl.esqlRefs.forEach(function (r) {
          if (!r.resolvedTo) return;
          var l = lay.files.filter(function (x) { return ACE.bar.byVPath(ws, r.resolvedTo) && x.fileId === ACE.bar.byVPath(ws, r.resolvedTo).id; })[0];
          if (l) add(fl.project, l.project, 'uses ESQL module ' + r.module);
        });
      });
    }
    var out = {};
    Object.keys(refs).forEach(function (k) { out[k] = Object.keys(refs[k].set).sort().map(function (t) { return { project: t, reasons: util.uniq(refs[k].why[t]) }; }); });
    return out;
  };

  /* Build an output package.
   * target: 'ace12' | 'ace13'
   * opts: {includeOriginalBar, barFile, reports:{name: text}, decompileHeader, facts, cancel, progress} */
  proj.buildPackage = async function (ws, target, opts) {
    opts = opts || {};
    var lay = proj.layout(ws), w = new ACE.zip.Writer(), manifest = [], refs = proj.references(ws, opts.facts);
    var overlay = target === 'ace13' ? (ws.ws13 && ws.ws13.overlay) || {} : (ws.ws12 && ws.ws12.overlay) || {};
    var changed = [];
    function put(path, data, rec) {
      var bytes = typeof data === 'string' ? util.encodeUtf8(data) : data;
      w.add(path, bytes, { date: rec.mtime });
      manifest.push(Object.assign({ path: path, size: bytes.length }, rec));
    }
    // 1. project files (original bytes unless overlaid by an approved change)
    for (var i = 0; i < lay.files.length; i++) {
      var l = lay.files[i], f = ws.files.filter(function (x) { return x.id === l.fileId; })[0];
      if (!f) continue;
      if (!f.bytes) { manifest.push({ path: l.outPath, origin: 'missing', sourceVPath: f.vpath, note: 'NOT EXPORTED: ' + (f.extractError || 'no data') }); continue; }
      var ov = overlay[l.outPath];
      if (ov) {
        put('_original-before-changes/' + l.outPath, f.bytes, { origin: 'original', sourceVPath: f.vpath, sha256: f.sha256, note: 'unchanged copy of a file modified in this package' });
        put(l.outPath, ov.text, { origin: ov.origin || 'transformed', sourceVPath: f.vpath, note: ov.history.map(function (h) { return h.kind + ': ' + h.title; }).join('; ') });
        changed.push(l.outPath);
      } else put(l.outPath, f.bytes, { origin: 'original', sourceVPath: f.vpath, sha256: f.sha256, mtime: f.mtime, rawName: f.rawName !== f.path ? f.rawName : undefined });
      if (i % 50 === 0) { if (opts.cancel) opts.cancel.check(); await util.yieldUI(); }
    }
    // 2. generated .project files for applications / libraries
    lay.projects.forEach(function (p) {
      var g = proj.generatedProjectFile(ws, p, refs), gp = p.name + '/.project', gov = overlay[gp];
      if (g && g.text && gov) {
        // generated .project changed in the working copy (e.g. library conversion)
        put('_original-before-changes/' + gp, g.text, { origin: 'generated', note: 'unchanged generated copy of a file modified in this package' });
        put(gp, gov.text, { origin: 'transformed', note: g.note + ' | ' + gov.history.map(function (h) { return h.title; }).join('; ') });
        changed.push(gp);
      } else if (g && g.text) put(gp, g.text, { origin: 'generated', note: g.note });
      else if (g) manifest.push({ path: p.name + '/', origin: 'note', note: g.note });
    });
    // 2b. files created in the working copy that have no original (e.g. a missing descriptor added by the library conversion)
    Object.keys(overlay).forEach(function (path) {
      var o = overlay[path];
      if (w.has(path) || !o.history.length || !o.history[0].created) return;
      put(path, o.text, { origin: 'generated', note: o.history.map(function (h) { return h.title; }).join('; ') });
      changed.push(path);
    });
    // 3. Eclipse Java projects for decompiled / imported JARs (src, bin, Lib, .project, .classpath, .settings)
    var javaProjects = [];
    Object.keys(ws.decompiled || {}).forEach(function (sha) {
      var d = ws.decompiled[sha];
      var jr = (ws.jars || []).filter(function (j) { return j.sha256 === sha; })[0];
      if (!jr || !d.results || !d.results.some(function (r) { return r.source; })) return;
      javaProjects.push(d.projectName);
      var ep = ACE.eclipse.files(ws, jr, { target: target, overlay: overlay, keepOriginalJar: opts.keepOriginalJar !== false, includeExcluded: !!opts.libIncludeExcluded });
      ep.files.forEach(function (f) {
        if (w.has(f.path)) return;
        if (f.original) { put('_original-before-changes/' + f.path, f.original, { origin: 'decompiled', note: 'unchanged decompiled copy' }); changed.push(f.path); }
        put(f.path, f.data, { origin: f.origin, sourceVPath: d.occurrences[0], note: f.note });
      });
      put(d.projectName + '/PROJECT-RECOVERY-NOTES.txt', ACE.eclipse.notes(ws, jr, ep), { origin: 'report' });
    });
    // 4. BAR metadata, unassigned files, conflicts
    lay.metadata.concat(lay.unassigned).forEach(function (m) {
      var f = ws.files.filter(function (x) { return x.id === m.fileId; })[0];
      if (!f || !f.bytes) { manifest.push({ path: m.outPath, origin: 'missing', note: f ? f.extractError : 'missing' }); return; }
      put(m.outPath, f.bytes, { origin: /^_bar-metadata/.test(m.outPath) ? 'original-metadata' : 'original', sourceVPath: f.vpath, sha256: f.sha256, note: m.note });
    });
    // 5. excluded JAR list, reports, instructions
    if (opts.reports) Object.keys(opts.reports).forEach(function (name) { put('_workbench/' + name, opts.reports[name], { origin: 'report' }); });
    put('_workbench/IMPORT-INSTRUCTIONS.txt', proj.instructions(ws, target, lay, refs, javaProjects, changed), { origin: 'report' });
    if (opts.includeOriginalBar && opts.barFile) put('_original/' + ws.barName, new Uint8Array(await opts.barFile.arrayBuffer()), { origin: 'original', note: 'the BAR file exactly as loaded' });
    var manifestDoc = { tool: 'IBM ACE Migration Workbench ' + util.VERSION, target: target, generatedAt: util.nowIso(), bar: { name: ws.barName, size: ws.barSize, sha256: ws.barSha256 }, extractionComplete: ws.complete, projects: lay.projects.map(function (p) { return { name: p.name, type: p.type, references: refs[p.name] || [] }; }).concat(javaProjects.map(function (n) { return { name: n, type: 'java (decompiled)' }; })), notes: lay.notes, changedFiles: changed, files: manifest };
    w.add('MANIFEST.json', JSON.stringify(manifestDoc, null, 2));
    var blob = await w.build(opts.progress, opts.cancel);
    return { blob: blob, manifest: manifestDoc };
  };

  proj.instructions = function (ws, target, lay, refs, javaProjects, changed) {
    var V = window.ACE_VERSIONS;
    var t = (target === 'ace13' ? V.targetLabel : V.sourceLabel) + ' Toolkit';
    var L = [];
    L.push('IMPORT INSTRUCTIONS - ' + t, '='.repeat(60), '', 'Source BAR : ' + ws.barName + ' (sha256 ' + (ws.barSha256 || 'n/a') + ')', 'Generated  : ' + util.nowIso() + ' by IBM ACE Migration Workbench ' + util.VERSION, '');
    if (!ws.complete) L.push('WARNING: extraction was INCOMPLETE. See _workbench reports and MANIFEST.json entries with origin "missing".', '');
    L.push('1. Start the ' + t + ' with a NEW, empty workspace.');
    L.push('2. File > Import > General > Existing Projects into Workspace.');
    L.push('3. Choose "Select archive file", pick THIS ZIP, tick the projects below, and press Finish:');
    lay.projects.forEach(function (p) { L.push('     - ' + p.name + '  (' + p.type + ')' + ((refs[p.name] || []).length ? '  references: ' + refs[p.name].map(function (r) { return r.project; }).join(', ') : '')); });
    javaProjects.forEach(function (n) { L.push('     - ' + n + '  (Java project with DECOMPILED source)'); });
    L.push('   Folders starting with "_" are not Toolkit projects (metadata, reports, originals).', '');
    if (ws.inputKind === 'workspace') {
      L.push('4. Input was a Toolkit workspace ZIP: every .project, .classpath and .settings file is the ORIGINAL file (byte-identical, see sha256 in MANIFEST.json). Project references are the ones declared in those .project files.');
      Object.keys(refs).forEach(function (k) { refs[k].forEach(function (r) { if (r.reasons.some(function (x) { return /NOT IN THE INPUT/.test(x); })) L.push('   MISSING: ' + k + ' references project "' + r.project + '", which is not in the input ZIP. Import it from source control before building.'); }); });
      L.push('');
    } else
    L.push('4. The .project files were GENERATED by the workbench (the BAR does not contain them). Their natures and builders follow the standard Toolkit layout for applications and libraries. The project references were INFERRED from contained static libraries and from resolved subflow/ESQL references. If the Toolkit cannot find a resource: right-click the project > Properties > Project References.', '');
    if (javaProjects.length) {
      L.push('5. Java projects (' + javaProjects.join(', ') + ') contain DECOMPILED code, not the original source.');
      L.push('   The original JAR is still inside the library/application that deployed it, so the flows build and run unchanged.');
      L.push('   To build the JAR from the decompiled source instead: review/compile the Java project, add it as a project reference of the library that uses it, and delete the copied JAR from that library. Do not keep both: duplicate classes on the classpath.');
      L.push('');
    }
    if (target === 'ace13') {
      if (ws.inputKind === 'workspace') L.push('6. Original Java projects keep their original build settings (no compiler-compliance file was added). ACE 13 integration servers default to Java 17: set the JRE / compliance in the ' + V.targetLabel + ' Toolkit and rebuild (see MANUAL_REVIEW items in MIGRATION-REPORT).');
      else L.push('6. Decompiled Java projects are configured for Java 17 compliance (ACE 13 integration servers default to Java 17).');
      L.push('7. Files changed by approved migration fixes (' + changed.length + '):');
      changed.forEach(function (c) { L.push('     - ' + c + '   (unchanged copy in _original-before-changes/)'); });
      L.push('8. Work through _workbench/MIGRATION-CHECKLIST and MIGRATION-REPORT. Static analysis does NOT prove runtime compatibility. Build a new BAR in the ACE ' + V.target + ' Toolkit and test on an ACE ' + V.target + ' integration server.');
    } else {
      L.push('6. Original sources are byte-identical to the BAR entries (see sha256 in MANIFEST.json).');
    }
    L.push('', 'ITEMS THAT REQUIRE VALIDATION IN THE REAL IBM TOOLKIT / RUNTIME:', ' - that the projects import and build without errors', ' - that generated .project natures/builders are accepted', ' - that the ESQL compiles and flows validate', ' - that a BAR built from these projects deploys and behaves like the original');
    if (lay.notes.length) { L.push('', 'NOTES:'); lay.notes.forEach(function (n) { L.push(' - ' + n); }); }
    return L.join('\r\n') + '\r\n';
  };
})(window.ACE);
